"""Read-only activity integration, using synthetic project/workflow fixtures."""
import runpy
from datetime import datetime, timedelta, timezone
from html.parser import HTMLParser
from pathlib import Path

fixture = runpy.run_path(str(Path(__file__).with_name('test_project_workspace.py')))
app = fixture['app']
from flask_login import login_user
from factoryos.extensions import db
from factoryos.models.user import User
from factoryos.modules.orders.models import Order
from factoryos.modules.projects.workspace_models import Audit, Member, WorkTime, ToolPartEvent, Report
from factoryos.modules.projects.services.activity_service import present_audits, ACTION_LABELS
from factoryos.core.models.change_log import ChangeLog
from factoryos.modules.admin.roles.models import Role
from factoryos.modules.admin.permissions.models import Permission


class Entries(HTMLParser):
    def __init__(self, html):
        super().__init__()
        self.entries = {}
        self.current = None
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'article' and 'data-project-activity' in attrs:
            self.current = int(attrs['data-project-activity'])
            self.entries[self.current] = []

    def handle_data(self, data):
        if self.current is not None:
            self.entries[self.current].append(data)

    def handle_endtag(self, tag):
        if tag == 'article':
            self.current = None

    def text(self, key):
        return ' '.join(' '.join(self.entries[key]).split())


with app.app_context():
    admin = db.session.merge(fixture['admin'])
    worker = db.session.merge(fixture['worker'])
    outsider = db.session.merge(fixture['outsider'])
    item = Order.query.filter_by(order_no='P-TEST').one()
    c = fixture['client'](admin)
    # Exact historical screenshot format: IDs and codes in before/current fields.
    settings = Audit(project_id=item.id, user_id=admin.id, action='Projekteinstellungen', data={
        'before': {'description': 'Test', 'leader': admin.id, 'project_kind': 'legacy', 'tool_no': None},
        'description': 'Test', 'leader': worker.id, 'project_kind': 'other', 'tool_no': None})
    secret = Order(order_no='PRIVATE-PROJECT', description='PRIVATE-DESCRIPTION', is_project=True,
        project_leader_id=admin.id, status='offen')
    db.session.add_all([settings, secret]); db.session.flush()
    secret_log = Audit(project_id=secret.id, user_id=admin.id, action='Projekt angelegt',
        data={'description': 'PRIVATE-DESCRIPTION'})
    db.session.add(secret_log)
    machine = ChangeLog(entity_type='machine', entity_id=1, entity_name='MACHINE-CENTRAL',
        action='update', user_id=admin.id, changes={'status': {'old': 'offen', 'new': 'aktiv'}},
        created_at=datetime.now(timezone.utc).replace(tzinfo=None)+timedelta(minutes=1))
    db.session.add(machine); db.session.commit()
    settings_id, secret_id, pid = settings.id, secret_log.id, item.id

    html = c.get(f'/projects/{pid}').get_data(as_text=True)
    rendered = Entries(html)
    line = rendered.text(settings_id)
    assert 'Projektleitung' in line and admin.username in line and worker.username in line and '→' in line
    assert 'Projektgrund' in line and 'Noch nicht eingeordnet' in line and 'Sonstiges' in line
    assert 'Beschreibung / Ziel' not in line and 'Werkzeug' not in line  # unchanged fields omitted
    for raw in ('"before"', 'project_kind', '"leader"', 'time_stop'):
        assert raw not in ' '.join(rendered.text(key) for key in rendered.entries)
    assert 'CET' in line or 'CEST' in line

    # All persisted audit action types generated by the workflow are readable.
    with app.test_request_context():
        login_user(admin)
        views = present_audits(Audit.query.filter_by(project_id=pid).all())
        assert all(view.action in ACTION_LABELS and view.lines for view in views)
        assert any(view.action_label == 'Arbeitszeit beendet / pausiert' for view in views)
        assert any(view.action_label == 'Projekt archiviert' for view in views)
        assert any(any(line['label'] == 'Fotos' and line['value'] == '1' for line in view.lines) for view in views)

    counts = (Audit.query.count(), ChangeLog.query.count(), WorkTime.query.count(), Report.query.count(), ToolPartEvent.query.count())
    response = c.get('/activity/?limit=all')
    assert response.status_code == 200, response.get_data(as_text=True)
    central = response.get_data(as_text=True)
    entries = Entries(central)
    assert settings_id in entries.entries and secret_id in entries.entries
    assert 'MACHINE-CENTRAL' in central and f'/projects/{pid}' in central
    assert central.index('MACHINE-CENTRAL') < central.index('data-project-activity=')
    assert entries.text(settings_id).endswith(rendered.text(settings_id))
    assert c.get('/activity/?limit=all').status_code == 200
    assert counts == (Audit.query.count(), ChangeLog.query.count(), WorkTime.query.count(), Report.query.count(), ToolPartEvent.query.count())
    projects_only = c.get('/activity/?type=project&limit=all').get_data(as_text=True)
    assert 'MACHINE-CENTRAL' not in projects_only and settings_id in Entries(projects_only).entries
    machines_only = c.get('/activity/?type=machine&limit=all').get_data(as_text=True)
    assert 'MACHINE-CENTRAL' in machines_only and not Entries(machines_only).entries
    for limit in ('5', '15', '25', '50'):
        page = c.get('/activity/?limit='+limit).get_data(as_text=True)
        assert len(Entries(page).entries)+page.count('class="changelog-item"') == min(int(limit), counts[0]+counts[1])
        assert f'value="{limit}" selected' in page
    assert c.get('/activity/?limit=invalid').status_code == 200

    # Global activities must not bypass personal project/source read rights.
    permission = Permission.query.filter_by(name='activity.view').first()
    if not permission:
        permission = Permission(name='activity.view', description='Aktivitäten ansehen')
        db.session.add(permission)
    worker.role.permissions.append(permission)
    role = Role(name='activity-only', active=True, permissions=[permission])
    reader = User(username='activity-only', password_hash='unused', active=True, role=role)
    db.session.add_all([role, reader]); db.session.commit()
    worker_html = fixture['client'](worker).get('/activity/?limit=all').get_data(as_text=True)
    assert settings_id in Entries(worker_html).entries
    assert 'PRIVATE-PROJECT' not in worker_html and 'PRIVATE-DESCRIPTION' not in worker_html
    assert 'Geschützte Fehlermeldung' in worker_html and 'FM-PROJECT' not in worker_html
    outsider_html = fixture['client'](outsider).get('/activity/?limit=all').get_data(as_text=True)
    assert not Entries(outsider_html).entries
    reader_html = fixture['client'](reader).get('/activity/?type=project&limit=all').get_data(as_text=True)
    assert not Entries(reader_html).entries and 'PRIVATE-DESCRIPTION' not in reader_html
    assert app.test_client().get('/activity/').status_code == 302
    all_role = Role(name='activity-project-reviewer', active=True, permissions=[permission,
        Permission.query.filter_by(name='projects.view').one(),
        Permission.query.filter_by(name='projects.view_all').one()])
    reviewer = User(username='project-reviewer', password_hash='unused', active=True, role=all_role)
    db.session.add_all([all_role, reviewer]); db.session.commit()
    reviewer_html = fixture['client'](reviewer).get('/activity/?type=project&limit=all').get_data(as_text=True)
    assert 'PRIVATE-PROJECT' in reviewer_html and secret_id in Entries(reviewer_html).entries

    # Older/minimal and unknown audit shapes never expose JSON or crash the view.
    with app.test_request_context():
        login_user(admin)
        old = Audit(id=999998, project_id=pid, user_id=admin.id, action='Projekteinstellungen',
            created_at=datetime.now(timezone.utc).replace(tzinfo=None), data={'before': {'leader': 999999}, 'leader': None})
        unknown = Audit(id=999999, project_id=pid, user_id=admin.id, action='future_action',
            created_at=datetime.now(timezone.utc).replace(tzinfo=None), data={})
        views = present_audits([old, unknown])
        assert views[0].lines[0]['old'] == 'Mitarbeiter #999999'
        assert views[0].lines[0]['value'] == 'Nicht zugewiesen'
        assert views[1].action_label == 'Projektänderung'
    # The general feed still works before optional project tables are installed.
    db.session.remove()
    Audit.__table__.drop(bind=db.engine)
    assert c.get('/activity/').status_code == 200
    print('PASS: readable historical/new project audits, names and purpose labels, local times, mixed chronological central feed, limits/type filters, source/project permissions, zero duplicates or database writes on read, unknown legacy events')
